function preferredLanguage(): Language {
  if (typeof navigator === 'undefined') return 'zh-TW';
  const language = navigator.language.toLowerCase();
  if (language.includes('zh-cn') || language.includes('zh-sg') || language.includes('hans')) return 'zh-CN';
  if (language.startsWith('en')) return 'en';
  return 'zh-TW';
}

export function useLanguage() {
  const [language, setLanguageState] = useState<Language>('zh-TW');

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY) as Language | null;
    setLanguageState(saved && dictionaries[saved] ? saved : preferredLanguage());
  }, []);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {}
  }, []);

  const t = useCallback((key: string) => dictionaries[language][key] ?? dictionaries.en[key] ?? key, [language]);

  return { language, setLanguage, t };
}
